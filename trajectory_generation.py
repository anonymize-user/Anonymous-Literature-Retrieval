def search_one_keyword(keyword):
    result = aminer_pro_search(keyword)
    return keyword, result
def calculate_hit_data(paper_id_list, paper_category, ground_truth_papers):
    hit_categories = []
    hit_data = {}
    for category, cat_obj in paper_category.items():
        gt_ids = cat_obj["ids"]     
        hit_papers = set(paper_id_list).intersection(set(gt_ids))
        hit_data[category] = {
            "hit_count": len(hit_papers),
            "total_count": len(gt_ids),
            "hit_papers": list(hit_papers)
        }

        if len(hit_papers) > 0:
            hit_categories.append(category)

    total_hit_papers = set(paper_id_list).intersection(set(ground_truth_papers))
    hit_data["overall"] = {
        "hit_count": len(total_hit_papers),
        "total_count": len(ground_truth_papers),
        "hit_papers": list(total_hit_papers)
    }
    print("Hit Data Summary:")
    for category, data in hit_data.items():
        print(f"Category: {category}")
        print(f"Hit proportion: {data['hit_count']}/{data['total_count']}")
    print(f"Overall Hit proportion: {hit_data['overall']['hit_count']}/{hit_data['overall']['total_count']}")
    print("=====================================")
    return len(hit_categories), hit_data["overall"]["hit_count"]

def calculate_general_category_score(paper_id_list, paper_category, ground_truth_papers):
    hit_proportion_infor = []
    for key, value in paper_category.items():
        ground_truth_ids = value.get("ids", [])
        if len(ground_truth_ids) == 0:
            hit_proportion = 0
        else:
            hit_count = len([pid for pid in paper_id_list if pid in ground_truth_ids])
            hit_proportion = hit_count / len(ground_truth_ids)
        hit_proportion_infor.append(hit_proportion)
    return sum(hit_proportion_infor) / len(hit_proportion_infor)

    

def paper_trajectory_generation(general_topic, initial_valid_keywords, initial_search_papers, paper_category, ground_truth_papers):
    # initial_valid_keywords is the general keywords that generated by general topic
    # initial_search_papers is the papers searched out by initial valid keywords
    # paper_category is the sectioned paper categories from the ground truth paper, which will seperatedly been analyzed
    # ground_truth_papers is the target ground truth paper list from the ground truth paper

    # Attention!!! We do not change the **ids** in paper_categories during the whole trajectory generation process because they are ground truth papers

    current_paper_ids = list(set(initial_search_papers))
    trajectory_recorder = []

    for i in range(5):
        print(f"================== Iteration {i+1} ==================")
        print("BEGIN NEW STEP CITATION")
        start = time.time()
        citation_paper_ids_list, non_hit_papers, hit_citation_paper_information = citation_adding(current_paper_ids, len(ground_truth_papers), general_topic, initial_valid_keywords, ground_truth_papers, 5) # Directly use citation generator to add papers
        end = time.time()
        print(f"Citation time: {end - start}")
        
        
        print("BEGIN NEW STEP KEYWORD SEARCH")
        start = time.time()
        # This styep use keyword generator to generate keywords and search papers
        # Each time we will generate keywords based on each section topic and keywords, then we will use selector to choose best papers
        # Next, we will use the papers selected to generate next step keywords for each categories
        new_keywords, keyword_paper_ids_list, non_hit_keywords, hit_keywords_information = keywords_adding(general_topic, paper_category, current_paper_ids, ground_truth_papers, 5) 
        end = time.time()
        print(f"Keyword time: {end - start}")
        sleep(2)
        recorded_new_keywords = new_keywords.copy()
        
        # Update keywords in paper_category
        for key, value in paper_category.items():
            paper_category[key]["past_keywords"].extend(paper_category[key]["keywords"])
            paper_category[key]["keywords"] = new_keywords.pop(0) 

        # Flatten 
        keyword_paper_ids_list = [pid for sublist in keyword_paper_ids_list for pid in sublist]
        current_already_hit_ids = []
        for id in current_paper_ids:
            if id in ground_truth_papers:
                current_already_hit_ids.append(id)
        keyword_paper_ids_list.extend(current_already_hit_ids)
        keyword_paper_ids_list = list(set(keyword_paper_ids_list))

        # Now we have citation_paper_ids_list and keyword_paper_ids_list, we need to choose better one
        citation_categories_hited, citation_num_hited = calculate_hit_data(citation_paper_ids_list, paper_category, ground_truth_papers)
        keyword_categories_hited, keyword_num_hited = calculate_hit_data(keyword_paper_ids_list, paper_category, ground_truth_papers)
        citation_general_category_hit = calculate_general_category_score(citation_paper_ids_list, paper_category, ground_truth_papers)
        keyword_general_category_hit = calculate_general_category_score(keyword_paper_ids_list, paper_category, ground_truth_papers)
        
        print("Citation general category hit:", citation_general_category_hit)
        print("Keyword general category hit:", keyword_general_category_hit)

        no_change = False
        if (citation_general_category_hit > keyword_general_category_hit):
            print("Citation step is better in categories hited")
            step_name = "citation"
            current_paper_ids = citation_paper_ids_list
        elif (citation_general_category_hit < keyword_general_category_hit):
            print("Keyword step is better in categories hited")
            step_name = "keyword search"
            current_paper_ids = keyword_paper_ids_list
        else:
            if (citation_categories_hited == 0 and keyword_categories_hited == 0 and citation_num_hited == 0 and keyword_num_hited == 0):
                no_change = True
                if random.random() < 0.5:
                    print("Both steps have zero hits → randomly choose CITATION")
                    step_name = "citation"
                    current_paper_ids = citation_paper_ids_list
                else:
                    print("Both steps have zero hits → randomly choose KEYWORD SEARCH")
                    step_name = "keyword search"
                    current_paper_ids = keyword_paper_ids_list
            else:
                if citation_categories_hited > keyword_categories_hited or (citation_categories_hited == keyword_categories_hited and citation_num_hited > keyword_num_hited):
                    print("Citation step is better in categories hited")
                    step_name = "citation"
                    current_paper_ids = citation_paper_ids_list
                else:
                    print("Keyword step is better in categories hited")
                    step_name = "keyword search"
                    current_paper_ids = keyword_paper_ids_list

        step_result = {}
        if step_name == "citation":
            step_result = {
            "Hit Categories": citation_categories_hited,
            "Total Categories": len(paper_category),
            "Overall Hit Papers": citation_num_hited,
            "Total Papers": len(ground_truth_papers),
            "Category Proportions": citation_categories_hited / len(paper_category),
            "Over-all Proportion": citation_num_hited / len(ground_truth_papers)
            }
        else:
            step_result = {
            "Hit Categories": keyword_categories_hited, 
            "Total Categories": len(paper_category),
            "Overall Hit Papers": keyword_num_hited,
            "Total Papers": len(ground_truth_papers),
            "Category Proportions": keyword_categories_hited / len(paper_category),
            "Over-all Proportion": keyword_num_hited / len(ground_truth_papers)
            }
        
        
        if no_change:
            step_information = {
            "mention": no_change,
            "step_name": step_name,
            "step_result": step_result,
            "current_paper_ids": current_paper_ids.copy(),
            "new_keywords": recorded_new_keywords
            }
        else:
            if step_name == "citation":
                step_information = {
                "step_name": step_name,
                "step_result": step_result,
                "current_paper_ids": current_paper_ids.copy(),
                "non_hit_papers": non_hit_papers.copy(),
                "hit_paper_information": hit_citation_paper_information.copy()
                }
            else:
                step_information = {
                "step_name": step_name,
                "step_result": step_result,
                "non hit keywords": non_hit_keywords.copy(),
                "current_paper_ids": current_paper_ids.copy(),
                "new_keywords": recorded_new_keywords,
                "hit_paper_information": hit_keywords_information.copy()
                }

        trajectory_recorder.append(step_information)
    
    final_papers = list(set(current_paper_ids))

    cat, overall = calculate_hit_data(final_papers, paper_category, ground_truth_papers)
    print(f"Final Result: Hit {cat} categories, Overall hit {overall} papers")
    print(f"Category Proportions: {cat / len(paper_category)}")
    print(f"Over-all Proportion: {overall / len(ground_truth_papers)}")
    return final_papers, paper_category, trajectory_recorder, cat, overall


